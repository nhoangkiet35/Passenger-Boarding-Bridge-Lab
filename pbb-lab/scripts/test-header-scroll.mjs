import assert from 'node:assert/strict';
import { installHeaderScroll } from '../lib/headerScroll.ts';
const listeners=new Map(),headerListeners=new Map(),classes=new Set();
let pending=null,menuOpen=false,focused=false;
globalThis.window={scrollY:0,addEventListener:(name,fn)=>listeners.set(name,fn),removeEventListener:name=>listeners.delete(name),requestAnimationFrame:fn=>{pending=fn;return 1;},cancelAnimationFrame:()=>{pending=null;}};
globalThis.document={activeElement:null};
const header={classList:{remove:name=>classes.delete(name),toggle:(name,on)=>on?classes.add(name):classes.delete(name)},contains:()=>focused,querySelector:()=>menuOpen?{}:null,addEventListener:(name,fn)=>headerListeners.set(name,fn),removeEventListener:name=>headerListeners.delete(name)};
const cleanup=installHeaderScroll(header);
const scroll=y=>{window.scrollY=y;listeners.get('scroll')();const run=pending;pending=null;run();};
scroll(70);assert(!classes.has('header-hidden'),'visible near top');
scroll(100);assert(classes.has('header-hidden'),'hide scrolling down');
scroll(96);assert(classes.has('header-hidden'),'ignore small scroll jitter');
scroll(89);assert(!classes.has('header-hidden'),'show scrolling up');
menuOpen=true;scroll(200);assert(!classes.has('header-hidden'),'keep open menu visible');
menuOpen=false;scroll(220);assert(classes.has('header-hidden'));
focused=true;headerListeners.get('focusin')();assert(!classes.has('header-hidden'),'keyboard focus restores header');
scroll(250);assert(!classes.has('header-hidden'));
focused=false;scroll(300);assert(classes.has('header-hidden'));
scroll(0);assert(!classes.has('header-hidden'),'always restore at top');
cleanup();assert.equal(listeners.size,0);assert.equal(headerListeners.size,0);
console.log('PASS header scroll direction, jitter threshold, menu, keyboard focus, top and cleanup');
